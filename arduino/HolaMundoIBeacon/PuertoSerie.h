#ifndef PUERTOSERIE_H_INCLUIDO
#define PUERTOSERIE_H_INCLUIDO

#include <Arduino.h>

// --------------------------------------------------------------
// --------------------------------------------------------------
class PuertoSerie {

  // ............................................................
  // ............................................................
private:

  long velocidad;

  // ............................................................
  // ............................................................
public:

  // ............................................................
  // ............................................................
  PuertoSerie( long velocidad ) : velocidad( velocidad ) {
	Serial.begin( velocidad );
  } // ()

  // ............................................................
  // Espera (con un máximo de 3 segundos) a que el puerto serie
  // esté listo. No espera indefinidamente para no bloquear la
  // placa cuando funciona alimentada por batería (sin USB).
  // ............................................................
  void esperarDisponible() {
	unsigned long inicio = millis();
	while ( !Serial  &&  (millis() - inicio) < 3000 ) {
	  delay( 10 );
	}
  } // ()

  // ............................................................
  // ............................................................
  void escribir( const char * texto ) {
	Serial.print( texto );
  } // ()

  // ............................................................
  // ............................................................
  void escribir( int valor ) {
	Serial.print( valor );
  } // ()

}; // class

// --------------------------------------------------------------
// Función global de espera, usada desde el .ino, Publicador, etc.
// --------------------------------------------------------------
inline void esperar( unsigned long ms ) {
  delay( ms );
} // ()

// --------------------------------------------------------------
// --------------------------------------------------------------
#endif
