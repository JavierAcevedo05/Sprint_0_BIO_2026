#ifndef LED_H_INCLUIDO
#define LED_H_INCLUIDO

#include <Arduino.h>

// --------------------------------------------------------------
// --------------------------------------------------------------
class LED {

  // ............................................................
  // ............................................................
private:

  int pin;

  // ............................................................
  // ............................................................
public:

  // ............................................................
  // ............................................................
  LED( int pin ) : pin( pin ) {
	pinMode( pin, OUTPUT );
	digitalWrite( pin, LOW );
  } // ()

  // ............................................................
  // Enciende el LED durante "ms" milisegundos y lo apaga.
  // ............................................................
  void brillar( int ms ) {
	digitalWrite( pin, HIGH );
	delay( ms );
	digitalWrite( pin, LOW );
  } // ()

}; // class

// --------------------------------------------------------------
// --------------------------------------------------------------
#endif
